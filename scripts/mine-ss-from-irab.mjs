#!/usr/bin/env node
// Mine sentence-structure (qr_ss_*) rows for a surah from the iʿrāb books in
// km_quran, with nuanced multiple readings reconciled across all books.
//
// Reads (via `wrangler d1 execute km_quran --remote --json`):
//   - qr_word_occurrences  (the universal token layer)
//   - qr_irab_book_entries (the raw iʿrāb book layer; mapped_from)
// Emits an idempotent seed file:
//   database/seeds/seed-qr-surah{N}-ss.sql
//
// The emitted SQL is reviewed before apply; the only fuzzy step is the
// fragment→word alignment (step 2 in docs/quran-ss-irab-mining.md). See that
// doc for the full pipeline. This is the scaffold that produced 39:1 by hand;
// running it fills 39:2–75 once iʿrāb word-linking is acceptable.
//
// Usage: node scripts/mine-ss-from-irab.mjs 39

import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

const surah = Number(process.argv[2]);
if (!surah) { console.error('usage: mine-ss-from-irab.mjs <surah>'); process.exit(1); }

const CONFIG = 'workers/quran/wrangler.toml';

function d1(sql) {
  const out = execFileSync('wrangler', [
    'd1', 'execute', 'km_quran', '--remote', '--config', CONFIG, '--json', '--command', sql,
  ], { encoding: 'utf8', maxBuffer: 1 << 28 });
  return JSON.parse(out)[0].results;
}

// Normalize Arabic for matching: strip diacritics, tatweel, leading al-, unify alef/ya/ta-marbuta.
const normalize = (s) => (s || '')
  .replace(/[ً-ْٰـ]/g, '')
  .replace(/[آأإ]/g, 'ا')
  .replace(/ى/g, 'ي').replace(/ة/g, 'ه')
  .replace(/^ال/, '').trim();

const esc = (s) => s == null ? 'NULL' : `'${String(s).replace(/'/g, "''")}'`;

// Map a normalized iʿrāb role to the canonical syntactic_function + lx ref.
const ROLE = {
  'مبتدا': ['mubtada', 'AL:nahw:mubtada'],
  'خبر': ['khabar', 'AL:nahw:khabar'],
  'مضاف اليه': ['mudaf_ilayh', 'AL:nahw:mudaf_ilayh'],
  'فاعل': ['fail', 'AL:nahw:fail'],
  'مفعول به': ['maful_bihi', 'AL:nahw:maful_bihi'],
  'حال': ['hal', 'AL:nahw:hal'],
  'نعت': ['naat', 'AL:nahw:naat'],
  'بدل': ['badal', 'AL:nahw:badal'],
  'جار ومجرور': ['jar_majrur', 'AL:nahw:jar_majrur'],
};

const words = d1(`SELECT id, ayah, word_index, word_text_bare FROM qr_word_occurrences WHERE surah=${surah} ORDER BY ayah, word_index;`);
const irab = d1(`SELECT source_slug, ayah_from AS ayah, target_text_bare, grammar_role_norm, grammar_case_ar, mahal_ar, alternative_json FROM qr_irab_book_entries WHERE surah=${surah} ORDER BY ayah, entry_order;`);

const wordsByAyah = new Map();
for (const w of words) { (wordsByAyah.get(w.ayah) ?? wordsByAyah.set(w.ayah, []).get(w.ayah)).push(w); }

const out = [`-- Generated by scripts/mine-ss-from-irab.mjs for surah ${surah}.`,
  `-- Review fragment→word alignment before apply. See docs/quran-ss-irab-mining.md.`, ''];

for (const [ayah, ws] of wordsByAyah) {
  // Collect per-word role votes across books (single-word fragments only; multi-word
  // spans are aligned by longest normalized match and assigned to their head word).
  const votes = new Map(); // word_index -> Map(role -> Set(book))
  const ayahIrab = irab.filter((e) => e.ayah === ayah);
  for (const e of ayahIrab) {
    const role = (e.grammar_role_norm || '').trim();
    if (!ROLE[role]) continue;
    const target = normalize(e.target_text_bare);
    const hit = ws.find((w) => normalize(w.word_text_bare) === target);
    if (!hit) continue; // multi-word / unaligned fragment — left for review pass
    const m = votes.get(hit.word_index) ?? votes.set(hit.word_index, new Map()).get(hit.word_index);
    (m.get(role) ?? m.set(role, new Set()).get(role)).add(e.source_slug);
  }
  // Emit reconciled readings: majority = most-voted role; others = minority/contested.
  for (const [widx, roleMap] of votes) {
    const w = ws.find((x) => x.word_index === widx);
    const ranked = [...roleMap.entries()].sort((a, b) => b[1].size - a[1].size);
    ranked.forEach(([role, books], i) => {
      const [fn, lx] = ROLE[role];
      const minority = i > 0 ? 1 : 0;
      const contested = ranked.length > 1 ? 1 : 0;
      const rid = `QR:SR:${surah}:${ayah}:${widx}:${i}`;
      out.push(
        `INSERT OR REPLACE INTO qr_ss_scope_reading (id,scope_type,scope_id,scholar_ref,reading_type,lx_reading_type_ref,reading_text_ar,is_minority,is_contested) ` +
        `VALUES (${esc(rid)},'word',${esc(w.id)},${esc([...books].join(';'))},'irab',${esc(lx)},${esc(`${w.word_text_bare}: ${role}`)},${minority},${contested});`,
      );
    });
  }
}

const path = `database/seeds/seed-qr-surah${surah}-ss.sql`;
writeFileSync(path, out.join('\n') + '\n');
console.log(`wrote ${path} (${out.length - 3} reading rows; review alignment, then wrangler d1 execute --file)`);
